"""Differential migration gate: generated legacy cases vs the native backend.

Python is a test oracle only. No supplied presets or generated bytes are committed.
"""
import argparse
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
reference=ROOT/'tests/reference'
if reference.exists():
    sys.path.insert(0,str(reference))
    os.environ['PYTHONPATH']=str(reference)+os.pathsep+str(ROOT)
from cabdisabler.adapters import Registry,PRODUCTION
from cabdisabler.formats import PresetFormat
from tests.test_valuetree import nolly,legacy,node


def collect_cases(private_presets=None):
    cases={}
    original=Registry.identify
    def capture(self,data,*a,**kw):
        try:
            result=original(self,data,*a,**kw)
            if self.builtin:cases[data]=True
            return result
        except (ValueError,OSError):
            if self.builtin:cases[data]=False
            raise
    Registry.identify=capture
    suite=unittest.defaultTestLoader.discover(str(ROOT/'tests'),top_level_dir=str(ROOT))
    # Build metadata/runtime-layout tests describe the historical Python build,
    # not backend semantics. Keep parser/engine/backup/discovery/wizard gates.
    names=('test_formats','test_valuetree','test_engine','test_direct_write','test_backup',
           'test_discovery','test_copy_workflow','test_backend','test_authorization','test_cli','test_review_fixes')
    def selected(s):
        for item in s:
            if isinstance(item,unittest.TestSuite):yield from selected(item)
            elif any('.'+name+'.' in item.id() for name in names):yield item
    result=unittest.TextTestRunner(verbosity=1).run(unittest.TestSuite(selected(suite)))
    Registry.identify=original
    if not result.wasSuccessful():raise RuntimeError('Reference gate failed')
    for base in (nolly(),legacy(),node('future',[('cabActive',True),('data',b'\0\xff')])):
        for offset in range(len(base)):
            for data in (base[:offset],base[:offset]+bytes([base[offset]^0xff])+base[offset+1:]):
                try:PRODUCTION.identify(data);cases[data]=True
                except ValueError:cases[data]=False
    # Exercise the deliberately reduced Expat feature configuration independently.
    xml=b'<refactor name="A &amp; B" cabActive="true"><note>&quot;&#169;&#x1f600;</note></refactor>'
    extra=[xml, b'\xff\xfe'+xml.decode().encode('utf-16le'), b'\xfe\xff'+xml.decode().encode('utf-16be'),
           b'<refactor xmlns:t="urn:test" cabActive="1"><t:note>text</t:note></refactor>',
           b'<!DOCTYPE refactor><refactor cabActive="true"/>',
           b'<!DOCTYPE refactor SYSTEM "https://example.invalid/external.dtd"><refactor cabActive="true"/>',
           b'<refactor cabActive="true" name="&undefined;"/>',
           b'<refactor cabActive="&#49;"/>']
    for data in extra:
        try: PRODUCTION.identify(data); cases[data]=True
        except ValueError: cases[data]=False
    private=0
    if private_presets:
        for p in private_presets.rglob('*.xml'):
            data=p.read_bytes()
            try:PRODUCTION.identify(data);cases[data]=True;private+=1
            except ValueError:cases[data]=False
    return cases, result.testsRun, private


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--backend',type=Path,required=True);parser.add_argument('--private-presets',type=Path);parser.add_argument('--report',type=Path,required=True);args=parser.parse_args()
    cases, reference_tests, private = collect_cases(args.private_presets)
    binary=str(args.backend.resolve())
    with tempfile.TemporaryDirectory(prefix='cab-native-diff-') as directory:
        root=Path(directory);paths=[];expected=[]
        for i,(data,accepted) in enumerate(cases.items()):
            p=root/f'{i}.xml';p.write_bytes(data);paths.append(p);expected.append(accepted)
        native=[]
        for start in range(0,len(paths),100):
            run=subprocess.run([binary,'inspect',*map(str,paths[start:start+100])],capture_output=True,text=True,check=True)
            native.extend(json.loads(line) for line in run.stdout.splitlines())
        assert len(native)==len(paths)
        for i,(info,accepted) in enumerate(zip(native,expected)):
            assert bool(info.get('adapter'))==accepted,(i,info,accepted)
        valid=[(p,data) for p,(data,accepted) in zip(paths,cases.items()) if accepted]
        for desired in (False,True):
            for p,data in valid:p.write_bytes(data)
            for start in range(0,len(valid),100):
                batch=valid[start:start+100]
                subprocess.run([binary,'edit','enable' if desired else 'disable',*map(lambda pair:str(pair[0]),batch),'--apply'],stdout=subprocess.DEVNULL,check=True)
            for p,data in valid:
                adapter,_=PRODUCTION.identify(data)
                assert p.read_bytes()==adapter.patch(data,desired),'Byte-span differential mismatch'
    report=dict(reference_tests=reference_tests,generated_and_private_inputs=len(cases),accepted=sum(expected),rejected=len(cases)-sum(expected),private_exports=private,exact_enabled_and_disabled_bytes=True,scope='host C++ backend vs test-only Python oracle; native platform UI/UAC not established')
    args.report.write_text(json.dumps(report,indent=2)+'\n');print(json.dumps(report))


if __name__=='__main__':main()
